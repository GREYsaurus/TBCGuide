// for the spell id of each rank, so text always matches the running client.

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.VisualBasic.FileIO;

namespace TBCGuideTools
{
    public static class Csv
    {
        public static List<Dictionary<string, string>> Read(string path)
        {
            var rows = new List<Dictionary<string, string>>();
            using (var p = new TextFieldParser(path, Encoding.UTF8))
            {
                p.TextFieldType = FieldType.Delimited;
                p.SetDelimiters(",");
                p.HasFieldsEnclosedInQuotes = true;
                string[] header = p.ReadFields();
                while (!p.EndOfData)
                {
                    var f = p.ReadFields();
                    var d = new Dictionary<string, string>();
                    for (int k = 0; k < header.Length && k < f.Length; k++) d[header[k]] = f[k];
                    rows.Add(d);
                }
            }
            return rows;
        }

        public static int I(Dictionary<string, string> r, string k)
        {
            string v;
            if (!r.TryGetValue(k, out v) || string.IsNullOrEmpty(v)) return 0;
            long l;
            return long.TryParse(v, NumberStyles.Integer, CultureInfo.InvariantCulture, out l) ? (int)l : 0;
        }
    }

    public sealed class TalentRow
    {
        public int Id, Tab, Tier, Col, ClassId;
        public List<int> Spells = new List<int>();
        public int PrereqTalent, PrereqRank;
        public string Name;
    }

    public static class ClientTables
    {
        public static readonly Dictionary<int, string> ClassFile = new Dictionary<int, string> {
            {1,"WARRIOR"},{2,"PALADIN"},{3,"HUNTER"},{4,"ROGUE"},{5,"PRIEST"},{7,"SHAMAN"},{8,"MAGE"},{9,"WARLOCK"},{11,"DRUID"} };
        public static readonly Dictionary<int, string> RaceFile = new Dictionary<int, string> {
            {1,"Human"},{2,"Orc"},{3,"Dwarf"},{4,"NightElf"},{5,"Scourge"},{6,"Tauren"},{7,"Gnome"},{8,"Troll"},{10,"BloodElf"},{11,"Draenei"} };

        public static string Export(string db2Dir, string addOnDir, string build)
        {
            var names = new Dictionary<int, string>();
            foreach (var r in Csv.Read(Path.Combine(db2Dir, "SpellName.csv")))
            {
                string n;
                if (r.TryGetValue("Name_lang", out n)) names[Csv.I(r, "ID")] = n;
            }
            var tabs = Csv.Read(Path.Combine(db2Dir, "TalentTab.csv"));
            var talents = new List<TalentRow>();
            foreach (var r in Csv.Read(Path.Combine(db2Dir, "Talent.csv")))
            {
                var t = new TalentRow
                {
                    Id = Csv.I(r, "ID"), Tab = Csv.I(r, "TabID"), Tier = Csv.I(r, "TierID"), Col = Csv.I(r, "ColumnIndex"),
                    ClassId = Csv.I(r, "ClassID"), PrereqTalent = Csv.I(r, "PrereqTalent_0"), PrereqRank = Csv.I(r, "PrereqRank_0")
                };
                for (int k = 0; k < 9; k++) { int s = Csv.I(r, "SpellRank_" + k); if (s > 0) t.Spells.Add(s); }
                if (t.Spells.Count == 0) continue;
                string nm;
                t.Name = names.TryGetValue(t.Spells[0], out nm) ? nm : ("Talent " + t.Id);
                talents.Add(t);
            }

            var sb = new StringBuilder();
            sb.Append("-- TBCGuide - talent trees for the TBC Anniversary client\n");
            sb.Append("-- GENERATED by tools/build.ps1 import-client from client DB2 exports (build " + build + ").\n");
            sb.Append("-- DO NOT EDIT BY HAND. Positions/ranks/prereqs are game data; descriptions come from the live client tooltip.\n");
            sb.Append("-- Fields per talent: id, name, tier (1-9), column (1-4), ranks, spells{per rank}, prereq{talentId, rank} or nil\n");
            sb.Append("local _, ns = ...\n");
            sb.Append("ns.TalentTrees = ns.TalentTrees or {}\n");
            sb.Append("ns.TalentTrees.build = " + LuaWriter.Str(build) + "\n");
            sb.Append("local T = ns.TalentTrees\n");
            int total = 0;
            var summary = new List<string>();
            foreach (var cls in ClassFile.OrderBy(c => c.Value))
            {
                int mask = 1 << (cls.Key - 1);
                var classTabs = tabs.Where(r => (Csv.I(r, "ClassMask") & mask) != 0 && Csv.I(r, "Field_4_4_0_53627_004") != 0)
                                    .OrderBy(r => Csv.I(r, "OrderIndex")).ToList();
                // Pet talent tabs have ClassMask 0; class tabs must number exactly 3.
                classTabs = classTabs.Where(r => Csv.I(r, "ClassMask") == mask).ToList();
                sb.Append("T." + cls.Value + " = {\n");
                int tabNo = 0;
                foreach (var tab in classTabs)
                {
                    tabNo++;
                    int tabId = Csv.I(tab, "ID");
                    var list = talents.Where(t => t.Tab == tabId).OrderBy(t => t.Tier).ThenBy(t => t.Col).ToList();
                    sb.Append("  {id=" + tabId + ",name=" + LuaWriter.Str(tab["Name_lang"]) + ",background=" + LuaWriter.Str(tab["BackgroundFile"]) +
                              ",icon=" + Csv.I(tab, "SpellIconID") + ",talents={\n");
                    foreach (var t in list)
                    {
                        sb.Append("    {id=" + t.Id + ",name=" + LuaWriter.Str(t.Name) + ",tier=" + (t.Tier + 1) + ",column=" + (t.Col + 1) +
                                  ",ranks=" + t.Spells.Count + ",spells={" + string.Join(",", t.Spells.Select(s => s.ToString(CultureInfo.InvariantCulture)).ToArray()) + "}");
                        if (t.PrereqTalent > 0) sb.Append(",prereq={" + t.PrereqTalent + "," + (t.PrereqRank + 1) + "}");
                        sb.Append("},\n");
                        total++;
                    }
                    sb.Append("  }},\n");
                    summary.Add(cls.Value + "/" + tab["Name_lang"] + ": " + list.Count + " talents");
                }
                sb.Append("}\n");
                if (tabNo != 3) summary.Add("WARNING: " + cls.Value + " has " + tabNo + " talent tabs");
            }
            string outDir = Path.Combine(addOnDir, "Talents", "Data");
            Directory.CreateDirectory(outDir);
            File.WriteAllText(Path.Combine(outDir, "TalentTrees.lua"), sb.ToString(), new UTF8Encoding(false));

            // ---- race/class legality ----
            var combos = Csv.Read(Path.Combine(db2Dir, "CharBaseInfo.csv"));
            var races = Csv.Read(Path.Combine(db2Dir, "ChrRaces.csv"));
            var rc = new StringBuilder();
            rc.Append("-- TBCGuide - playable race/class combinations\n");
            rc.Append("-- GENERATED by tools/build.ps1 import-client from client CharBaseInfo/ChrRaces (build " + build + "). DO NOT EDIT.\n");
            rc.Append("local _, ns = ...\n");
            rc.Append("ns.RaceClass = {\n  build = " + LuaWriter.Str(build) + ",\n  races = {\n");
            int comboCount = 0;
            foreach (var race in RaceFile.OrderBy(r => r.Key))
            {
                var row = races.First(r => Csv.I(r, "ID") == race.Key);
                string faction = Csv.I(row, "Alliance") == 0 ? "Alliance" : "Horde";
                var classes = combos.Where(c => Csv.I(c, "RaceID") == race.Key).Select(c => Csv.I(c, "ClassID"))
                                    .Where(c => ClassFile.ContainsKey(c)).Distinct().OrderBy(c => c).Select(c => ClassFile[c]).ToList();
                comboCount += classes.Count;
                rc.Append("    " + race.Value + " = {id=" + race.Key + ",faction=" + LuaWriter.Str(faction) + ",name=" + LuaWriter.Str(row["Name_lang"]) +
                          ",classes={" + string.Join(",", classes.Select(c => LuaWriter.Str(c)).ToArray()) + "}},\n");
            }
            rc.Append("  },\n}\n");
            File.WriteAllText(Path.Combine(addOnDir, "Database", "RaceClass.lua"), rc.ToString(), new UTF8Encoding(false));
            summary.Add("talents total: " + total);
            summary.Add("race/class combinations: " + comboCount);
            return string.Join(Environment.NewLine, summary.ToArray());
        }
    }
}
